def lerp_c(a, b, t):
    return tuple(int(round(a[i] + (b[i] - a[i]) * t)) for i in range(4))

def shade(c, f):
    """f>0 lighten toward white, f<0 darken toward black."""
    if f >= 0:
        return lerp_c(c, (255, 255, 255, c[3]), f)
    return lerp_c(c, (0, 0, 0, c[3]), -f)

