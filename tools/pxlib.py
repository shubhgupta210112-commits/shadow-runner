def new(w, h, fill=(0, 0, 0, 0)):
    im = Image.new('RGBA', (w, h), fill)
    return im, ImageDraw.Draw(im)

def alpha_mask(im):
    return np.array(im)[..., 3] > 0

def rimlight(im, hl=0.28, sh=0.30):
    """Light from top-left: lighten opaque edge pixels facing up/left,
    darken ones facing down/right. Done before outlining."""
    a = np.array(im).astype(np.int32)
    m = a[..., 3] > 0
    h, w = m.shape
    pad = np.pad(m, 1)
    up = ~pad[0:h, 1:w + 1]
    left = ~pad[1:h + 1, 0:w]
    down = ~pad[2:h + 2, 1:w + 1]
    right = ~pad[1:h + 1, 2:w + 2]
    lit = m & (up | left)
    dark = m & (down | right) & ~lit
    for mask, f in ((lit, hl), (dark, -sh)):
        for c in range(3):
            ch = a[..., c]
            if f >= 0:
                ch = np.where(mask, ch + (255 - ch) * f, ch)
            else:
                ch = np.where(mask, ch * (1 + f), ch)
            a[..., c] = ch
    return Image.fromarray(np.clip(a, 0, 255).astype(np.uint8), 'RGBA')

def outline(im, color=None, diag=False):
    """Add a 1px outline around opaque pixels (expands canvas content by 1px)."""
    a = np.array(im)
    m = a[..., 3] > 0
    h, w = m.shape
    pad = np.pad(m, 1)
    n = pad[0:h, 1:w + 1] | pad[2:h + 2, 1:w + 1] | pad[1:h + 1, 0:w] | pad[1:h + 1, 2:w + 2]
    if diag:
        n = n | pad[0:h, 0:w] | pad[0:h, 2:w + 2] | pad[2:h + 2, 0:w] | pad[2:h + 2, 2:w + 2]
    edge = n & ~m
    if color is None:
        color = PAL['void']
    a[edge] = color
    return Image.fromarray(a, 'RGBA')

def auto_outline(im, color=None):
    """Colored outline: darker version of neighboring pixel color for a soft look."""
    a = np.array(im)
    m = a[..., 3] > 0
    h, w = m.shape
    out = a.copy()
    pm = np.pad(m, 1)
    pa = np.pad(a, ((1, 1), (1, 1), (0, 0)))
    ys, xs = np.nonzero(~m)
    for y, x in zip(ys, xs):
        best = None
        for dy, dx in ((-1, 0), (1, 0), (0, -1), (0, 1)):
            if pm[y + 1 + dy, x + 1 + dx]:
                best = pa[y + 1 + dy, x + 1 + dx]
                break
        if best is not None:
            c = (best[:3].astype(np.float32) * 0.28 + np.array([8, 6, 20]) * 0.72)
            out[y, x] = (int(c[0]), int(c[1]), int(c[2]), 255)
    return Image.fromarray(out, 'RGBA')

