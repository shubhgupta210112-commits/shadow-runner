def paste_center_bottom(dst, src, cx, bottom):
    x = cx - src.width // 2
    y = bottom - src.height
    dst.alpha_composite(src, (x, y))

def upscale(im, k):
    return im.resize((im.width * k, im.height * k), Image.NEAREST)

def glow_blob(size, color, power=2.0, alpha=255):
    """Radial soft glow sprite (not pixel art -- used for light-ish halos)."""
    im = Image.new('RGBA', (size, size), (0, 0, 0, 0))
    a = np.zeros((size, size, 4), np.uint8)
    yy, xx = np.mgrid[0:size, 0:size]
    d = np.sqrt((xx - size / 2 + 0.5) ** 2 + (yy - size / 2 + 0.5) ** 2) / (size / 2)
    v = np.clip(1 - d, 0, 1) ** power
    a[..., 0] = color[0]
    a[..., 1] = color[1]
    a[..., 2] = color[2]
    a[..., 3] = (v * alpha).astype(np.uint8)
    return Image.fromarray(a, 'RGBA')

def strip(frames):
    """Concatenate equal-size frames horizontally."""
    w, h = frames[0].size
    out = Image.new('RGBA', (w * len(frames), h), (0, 0, 0, 0))
    for i, f in enumerate(frames):
        out.alpha_composite(f, (i * w, 0))
    return out

def sheet(rows):
    """rows: list of lists of frames -> 2D sheet. Rows padded to max length."""
    w, h = rows[0][0].size
    cols = max(len(r) for r in rows)
    out = Image.new('RGBA', (w * cols, h * len(rows)), (0, 0, 0, 0))
    for ri, r in enumerate(rows):
        for ci, f in enumerate(r):
            out.alpha_composite(f, (ci * w, ri * h))
    return out

def periodic_noise(width, height, cycles_x, seed, octaves=4, rough=0.5):
    """Horizontally-periodic 1D height profile (list of floats 0..1 length=width)."""
    rng = random.Random(seed)
    prof = np.zeros(width)
    amp = 1.0
    tot = 0
    for o in range(octaves):
        c = cycles_x * (2 ** o)
        ph = rng.random() * math.tau
        ph2 = rng.random() * math.tau
        x = np.arange(width) / width * math.tau * c
        prof += amp * (np.sin(x + ph) * 0.65 + np.sin(x * 2.17 + ph2) * 0.35)
        tot += amp
        amp *= rough
    prof = (prof / tot + 1) / 2
    return prof
